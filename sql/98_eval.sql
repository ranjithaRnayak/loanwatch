/*  ===========================================================
    98_eval.sql
    Evaluation queries for LoanWatch — rerunnable
    Produces the numbers used in docs/EVALUATION.md
    ===========================================================  */

USE DATABASE LOANWATCH;
USE WAREHOUSE LW_XS;

-- ============================================================
-- (a) Signal quality
-- ============================================================

-- a.1  Signals per planted persona
SELECT b.BORROWER_ID, b.BORROWER_NAME, b.CONSTITUTION,
       COUNT(s.EWS_CODE) AS OPEN_SIGNALS,
       LISTAGG(s.EWS_CODE, ', ') WITHIN GROUP (ORDER BY s.EWS_CODE) AS EWS_CODES,
       MAX(a.ASSET_CLASS) AS CURRENT_ASSET_CLASS,
       MAX(a.MAX_DPD)     AS MAX_DPD
FROM RAW.BORROWERS b
LEFT JOIN (SELECT * FROM OUT.SIGNALS WHERE STATUS = 'OPEN') s
       ON s.BORROWER_ID = b.BORROWER_ID
LEFT JOIN (SELECT BORROWER_ID, ASSET_CLASS, MAX_DPD
           FROM CORE.ASSET_CLASS_DAILY
           WHERE AS_OF_DATE = (SELECT MAX(AS_OF_DATE) FROM CORE.ASSET_CLASS_DAILY)) a
       ON a.BORROWER_ID = b.BORROWER_ID
WHERE b.IS_PERSONA = TRUE
GROUP BY b.BORROWER_ID, b.BORROWER_NAME, b.CONSTITUTION
ORDER BY b.BORROWER_ID;

-- a.2  Non-planted signal summary
SELECT
  (SELECT COUNT(DISTINCT BORROWER_ID) FROM OUT.SIGNALS WHERE STATUS='OPEN' AND BORROWER_ID NOT LIKE 'B-P%') AS borrowers_with_any_signal,
  (SELECT COUNT(DISTINCT BORROWER_ID) FROM OUT.SIGNALS WHERE STATUS='OPEN' AND SEVERITY='HIGH' AND BORROWER_ID NOT LIKE 'B-P%') AS borrowers_with_high_signal,
  (SELECT COUNT(*) FROM RAW.BORROWERS WHERE IS_PERSONA = FALSE) AS total_non_planted,
  ROUND(100.0 * (SELECT COUNT(DISTINCT BORROWER_ID) FROM OUT.SIGNALS WHERE STATUS='OPEN' AND BORROWER_ID NOT LIKE 'B-P%')
        / NULLIF((SELECT COUNT(*) FROM RAW.BORROWERS WHERE IS_PERSONA = FALSE), 0), 2) AS flag_rate_pct;

-- a.3  Non-planted signal breakdown by EWS code
SELECT EWS_CODE, COUNT(*) AS CNT, COUNT(DISTINCT BORROWER_ID) AS BORROWERS
FROM OUT.SIGNALS
WHERE STATUS = 'OPEN' AND BORROWER_ID NOT LIKE 'B-P%'
GROUP BY EWS_CODE
ORDER BY EWS_CODE;

-- a.4  Total signal counts
SELECT
  COUNT(*) AS total_open_signals,
  COUNT(DISTINCT BORROWER_ID) AS distinct_borrowers,
  SUM(CASE WHEN BORROWER_ID LIKE 'B-P%' THEN 1 ELSE 0 END) AS planted_signals,
  SUM(CASE WHEN BORROWER_ID NOT LIKE 'B-P%' THEN 1 ELSE 0 END) AS non_planted_signals
FROM OUT.SIGNALS
WHERE STATUS = 'OPEN';


-- ============================================================
-- (b) Agent accuracy — ground truth queries
-- ============================================================

-- b.1  SMA-2 count (Q5 ground truth)
SELECT COUNT(DISTINCT BORROWER_ID) AS sma2_count
FROM CORE.ASSET_CLASS_DAILY
WHERE ASSET_CLASS = 'SMA-2'
  AND AS_OF_DATE = (SELECT MAX(AS_OF_DATE) FROM CORE.ASSET_CLASS_DAILY);

-- b.2  Gross NPA ratio (Q7 ground truth)
SELECT
  ROUND(SUM(CASE WHEN ASSET_CLASS IN ('SUBSTANDARD','DOUBTFUL','LOSS') THEN EXPOSURE ELSE 0 END)
        / SUM(EXPOSURE) * 100, 2) AS gross_npa_pct
FROM CORE.ASSET_CLASS_DAILY
WHERE AS_OF_DATE = (SELECT MAX(AS_OF_DATE) FROM CORE.ASSET_CLASS_DAILY);

-- b.3  Fraud stats FY26 (Q8 ground truth)
SELECT METRIC, VALUE, UNIT, SOURCE
FROM REF.SYSTEM_BENCHMARKS
WHERE LOWER(METRIC) LIKE '%fraud%'
  AND AS_OF_DATE = '2026-03-31';

-- b.4  Borrowers with 2+ signals and total exposure (Q13 ground truth)
SELECT COUNT(DISTINCT s.BORROWER_ID) AS borrowers,
       ROUND(SUM(DISTINCT a.EXPOSURE)/1e7, 2) AS exposure_cr
FROM OUT.SIGNALS s
JOIN CORE.ASSET_CLASS_DAILY a ON a.BORROWER_ID = s.BORROWER_ID
  AND a.AS_OF_DATE = (SELECT MAX(AS_OF_DATE) FROM CORE.ASSET_CLASS_DAILY)
WHERE s.STATUS = 'OPEN'
AND s.BORROWER_ID IN (
  SELECT BORROWER_ID FROM OUT.SIGNALS WHERE STATUS='OPEN'
  GROUP BY BORROWER_ID HAVING COUNT(*) >= 2
);

-- b.5  Branch with most signals (Q14 ground truth)
SELECT b.HOME_BRANCH_ID, br.BRANCH_NAME, COUNT(*) AS signal_count
FROM OUT.SIGNALS s
JOIN RAW.BORROWERS b ON b.BORROWER_ID = s.BORROWER_ID
JOIN RAW.BRANCHES br ON br.BRANCH_ID = b.HOME_BRANCH_ID
WHERE s.STATUS = 'OPEN'
GROUP BY b.HOME_BRANCH_ID, br.BRANCH_NAME
ORDER BY signal_count DESC
LIMIT 5;

-- b.6  SMA-1 to SMA-2 migration Sep 2026 (Q10 ground truth)
SELECT COUNT(DISTINCT a.BORROWER_ID) AS migrated_count
FROM CORE.ASSET_CLASS_DAILY a
JOIN CORE.ASSET_CLASS_DAILY b ON a.BORROWER_ID = b.BORROWER_ID
WHERE a.ASSET_CLASS = 'SMA-2' AND b.ASSET_CLASS = 'SMA-1'
  AND a.AS_OF_DATE = '2026-09-30'
  AND b.AS_OF_DATE = '2026-08-31';

-- b.7  Nandi Infra shared directors (Q12 ground truth)
SELECT DISTINCT cd.COUNTERPARTY_ID
FROM RAW.BORROWER_DIRECTORS bd
JOIN RAW.COUNTERPARTY_DIRECTORS cd ON bd.DIRECTOR_ID = cd.DIRECTOR_ID
WHERE bd.BORROWER_ID = 'B-P5';

-- b.8  Regulatory ground truths (Q6, Q15, Q16, Q17)
-- CRILC 7 days
SELECT DOC_CODE, CLAUSE_REF, LEFT(CHUNK_TEXT, 200) AS excerpt
FROM REF.REG_CHUNKS
WHERE LOWER(CHUNK_TEXT) LIKE '%crilc%' AND LOWER(CHUNK_TEXT) LIKE '%seven day%'
LIMIT 2;

-- 180-day fraud decision
SELECT DOC_CODE, CLAUSE_REF, LEFT(CHUNK_TEXT, 200) AS excerpt
FROM REF.REG_CHUNKS
WHERE LOWER(CHUNK_TEXT) LIKE '%180%day%' AND DOC_CODE = 'FRM24'
LIMIT 2;

-- NPA upgrade
SELECT DOC_CODE, CLAUSE_REF, LEFT(CHUNK_TEXT, 200) AS excerpt
FROM REF.REG_CHUNKS
WHERE LOWER(CHUNK_TEXT) LIKE '%upgrade%' AND LOWER(CHUNK_TEXT) LIKE '%standard%'
  AND DOC_CODE = 'IRACP25'
LIMIT 2;

-- CTR threshold
SELECT DOC_CODE, CLAUSE_REF, LEFT(CHUNK_TEXT, 200) AS excerpt
FROM REF.REG_CHUNKS
WHERE LOWER(CHUNK_TEXT) LIKE '%cash transaction report%'
  AND LOWER(CHUNK_TEXT) LIKE '%10 lakh%'
LIMIT 2;

-- b.9  Agent call timing from QUERY_HISTORY (run within 6 hours of agent eval)
SELECT
  ROW_NUMBER() OVER (ORDER BY START_TIME) AS Q,
  QUERY_ID,
  ROUND(TIMESTAMPDIFF('MILLISECOND', START_TIME, END_TIME)/1000.0, 1) AS SEC,
  REGEXP_SUBSTR(QUERY_TEXT, 'text":"([^"]+)', 1, 1, 'e') AS QUESTION
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE QUERY_TEXT LIKE '%DATA_AGENT_RUN%LOANWATCH_AGENT%text%'
  AND START_TIME >= DATEADD('day', -1, CURRENT_TIMESTAMP())
  AND TIMESTAMPDIFF('MILLISECOND', START_TIME, END_TIME) > 1000
ORDER BY START_TIME ASC;


-- ============================================================
-- (c) Governance
-- ============================================================

-- c.1  Policy inventory
SELECT POLICY_NAME, REF_COLUMN_NAME
FROM TABLE(INFORMATION_SCHEMA.POLICY_REFERENCES(
  ref_entity_name => 'LOANWATCH.RAW.BORROWERS', ref_entity_domain => 'TABLE'));

SELECT POLICY_NAME, REF_COLUMN_NAME
FROM TABLE(INFORMATION_SCHEMA.POLICY_REFERENCES(
  ref_entity_name => 'LOANWATCH.OUT.STR_DRAFTS', ref_entity_domain => 'TABLE'));

-- c.2  Role entitlements
SELECT * FROM GOV.ROLE_ENTITLEMENTS ORDER BY ROLE_NAME;

-- c.3  Region breakdown for LW_JUDGE scope
SELECT m.REGION, COUNT(*) AS borrower_count,
       ROUND(100.0 * COUNT(*) / (SELECT COUNT(*) FROM RAW.BORROWERS), 1) AS pct
FROM GOV.BORROWER_REGION m
GROUP BY m.REGION
ORDER BY m.REGION;

-- c.4  LW_JUDGE expected borrower count (SOUTH + WEST)
SELECT SUM(cnt) AS lw_judge_borrower_count
FROM (SELECT COUNT(*) AS cnt FROM GOV.BORROWER_REGION WHERE REGION IN ('SOUTH','WEST'));

-- c.5  Policy definitions (for audit)
SELECT GET_DDL('POLICY', 'LOANWATCH.GOV.MASK_PAN');
SELECT GET_DDL('POLICY', 'LOANWATCH.GOV.RAP_BORROWER_REGION');
SELECT GET_DDL('POLICY', 'LOANWATCH.GOV.RAP_STR_PRINCIPAL_OFFICER');
SELECT GET_DDL('FUNCTION', 'LOANWATCH.GOV.FN_CAN_VIEW_PII()');


-- ============================================================
-- (d) Cost
-- ============================================================

-- d.1  Credits by warehouse (last 7 days)
SELECT WAREHOUSE_NAME,
       ROUND(SUM(CREDITS_USED), 4)                AS TOTAL_CREDITS,
       ROUND(SUM(CREDITS_USED_COMPUTE), 4)         AS COMPUTE_CREDITS,
       ROUND(SUM(CREDITS_USED_CLOUD_SERVICES), 4)  AS CLOUD_CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE START_TIME >= DATEADD('day', -7, CURRENT_TIMESTAMP())
GROUP BY WAREHOUSE_NAME
ORDER BY TOTAL_CREDITS DESC;

-- d.2  Total credits and estimated cost
SELECT
  ROUND(SUM(CREDITS_USED), 4) AS TOTAL_CREDITS,
  ROUND(SUM(CREDITS_USED) * 3, 2) AS APPROX_USD_AT_3
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE START_TIME >= DATEADD('day', -7, CURRENT_TIMESTAMP());

-- d.3  Cortex function usage (may be empty due to ACCOUNT_USAGE latency)
SELECT FUNCTION_NAME, MODEL_NAME,
       COUNT(*) AS CALL_COUNT,
       ROUND(SUM(TOKENS), 0) AS TOTAL_TOKENS,
       ROUND(SUM(TOKEN_CREDITS), 6) AS TOTAL_CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_FUNCTIONS_USAGE_HISTORY
WHERE START_TIME >= DATEADD('day', -7, CURRENT_TIMESTAMP())
GROUP BY FUNCTION_NAME, MODEL_NAME
ORDER BY TOTAL_CREDITS DESC;

-- d.4  SP_RUN_SIGNALS timing
SELECT QUERY_ID, LEFT(QUERY_TEXT, 80) AS QUERY_SHORT,
       ROUND(TIMESTAMPDIFF('MILLISECOND', START_TIME, END_TIME)/1000.0, 1) AS SEC
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE QUERY_TEXT LIKE '%SP_RUN_SIGNALS%'
  AND START_TIME >= DATEADD('day', -7, CURRENT_TIMESTAMP())
ORDER BY START_TIME DESC
LIMIT 5;
